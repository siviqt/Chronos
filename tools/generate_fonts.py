#!/usr/bin/env python3
"""Generate committed PAX 2.2.2 fonts; no network or generation at build time.

Reproducible rasterizer: Pillow 12.3.0 / FreeType 2.14.3, fonttools 4.61.1.
See assets/fonts/README.md for provenance, coverage, metrics and regeneration.
"""
from pathlib import Path
import hashlib
import json
import re
from PIL import Image, ImageDraw, ImageFont, features
import PIL
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / 'assets/fonts'
OUT = ROOT / 'components/chronos_ui/assets/fonts'
# family, weight, pixel size, semantic role, coverage
SPECS = [
    ('Sans', 'Regular', 12, 'CAPTION', 'ascii'),
    ('Sans', 'Regular', 14, 'SECONDARY', 'ui'),
    ('Sans', 'Regular', 16, 'BODY', 'ui'),
    ('Sans', 'Medium', 16, 'BUTTON', 'ascii'),
    ('Sans', 'SemiBold', 18, 'SECTION', 'ascii'),
    ('Sans', 'Medium', 20, 'DATE', 'ascii'),
    ('Sans', 'SemiBold', 24, 'TITLE', 'ascii'),
    ('Mono', 'Medium', 16, 'TIME_SMALL', ' +-.0123456789:%'),
    ('Mono', 'Medium', 24, 'TIME_NORMAL', '0123456789:'),
    ('Mono', 'Medium', 28, 'TIME_MEDIUM', '0123456789:'),
    ('Mono', 'SemiBold', 56, 'TIME_LARGE', '.0123456789:'),
    ('Mono', 'SemiBold', 72, 'CLOCK_MAIN', '-0123456789:'),
]

def groups(cps):
    result = []
    for cp in sorted(cps):
        if result and cp == result[-1][-1] + 1:
            result[-1].append(cp)
        else:
            result.append([cp])
    return result


def main():
    if (PIL.__version__, features.version('freetype2')) != ('12.3.0', '2.14.3'):
        raise SystemExit('Use Pillow 12.3.0 with FreeType 2.14.3 for byte-identical outputs')
    OUT.mkdir(parents=True, exist_ok=True)
    coverage = json.loads((ASSETS / 'coverage.json').read_text())['ranges']
    ui = {c for a, b in coverage for c in range(a, b + 1) if c >= 32}
    compat = json.loads((ASSETS / 'compatibility-glyphs.json').read_text())
    declarations, aliases, manifest = [], [], []
    for family, weight, size, role, charset in SPECS:
        name = f'ibm_plex_{family.lower()}_{weight.lower()}_{size}'
        source = ASSETS / f'source/IBMPlex{family}-{weight}.ttf'
        font = ImageFont.truetype(str(source), size, layout_engine=ImageFont.Layout.BASIC)
        cmap = TTFont(source).getBestCmap()
        thai_source = ASSETS / 'source/IBMPlexSansThai-Regular.ttf'
        thai = ImageFont.truetype(str(thai_source), size, layout_engine=ImageFont.Layout.BASIC)
        thai_cmap = TTFont(thai_source).getBestCmap()
        cps = ui if charset == 'ui' else set(range(32, 127)) if charset == 'ascii' else set(map(ord, charset))
        # Shared baseline at the native ascender; all fonts use full line height.
        ascent, descent = font.getmetrics()
        line_height = ascent + descent
        pixels, dims = [], []
        min_top, max_bottom = 0, line_height
        for cp in sorted(cps):
            ch = chr(cp)
            if cp in cmap or cp in thai_cmap:
                f = font if cp in cmap else thai
                left, top, right, bottom = f.getbbox(ch, anchor='ls')
                img = Image.new('L', (max(1, right-left), max(1, bottom-top)))
                ImageDraw.Draw(img).text((-left, -top), ch, font=f, fill=255, anchor='ls')
                advance = round(f.getlength(ch))
                top += ascent
            else:
                # Only characters missing from both Plex sources use these
                # historic glyphs, merged into the same font/range API.
                d = compat[str(cp)]
                img = Image.new('L', (d['draw_w'], d['draw_h']))
                img.putdata(d['pixels'])
                img = img.resize((max(1, round(img.width*size/16)), max(1, round(img.height*size/16))), Image.Resampling.LANCZOS)
                left = round(d['draw_x']*size/16)
                top = round(d['draw_y']*size/16) + ascent - round(12*size/16)
                advance = round(d['measured_width']*size/16)
            min_top = min(min_top, top)
            max_bottom = max(max_bottom, top + img.height)
            index = len(pixels)
            for y in range(img.height):
                for x in range(0, img.width, 2):
                    lo = (img.getpixel((x, y)) + 8) // 17
                    hi = (img.getpixel((x+1, y)) + 8) // 17 if x+1 < img.width else 0
                    pixels.append(lo | hi << 4)
            assert -128 <= top <= 127 and 0 <= advance <= 255
            dims.append(f'{{.draw_x={left},.draw_y={top},.draw_w={img.width},.draw_h={img.height},.measured_width={advance},.index={index}}}')
        # Preserve tall accents/Thai marks instead of clipping to Latin metrics.
        if min_top < 0:
            dims = [re.sub(r'draw_y=(-?\d+)', lambda m: f'draw_y={int(m[1])-min_top}', d) for d in dims]
        ascent -= min_top
        line_height = max_bottom - min_top
        lines = ['/* Generated by tools/generate_fonts.py. IBM OFL: assets/fonts/LICENSE.txt.',
                 ' * Compatibility symbols: assets/fonts/LICENSE.compatibility. */', '#include "pax_gfx.h"',
                 f'static const uint8_t pixels[] = {{']
        lines += ['    '+','.join(map(str,pixels[i:i+24]))+',' for i in range(0,len(pixels),24)]
        lines += ['};', 'static const pax_bmpv_t dims[] = {'] + ['    '+d+',' for d in dims] + ['};', 'static const pax_font_range_t ranges[] = {']
        index = 0
        for group in groups(cps):
            lines.append(f'    {{.type=PAX_FONT_TYPE_BITMAP_VAR,.start={group[0]},.end={group[-1]},.bitmap_var={{.glyphs=pixels,.dims=dims+{index},.height={line_height},.bpp=4}}}},')
            index += len(group)
        lines += ['};', f'const pax_font_t {name} = {{.name="CHRONOS {family} {weight} {size}",.n_ranges=sizeof(ranges)/sizeof(*ranges),.ranges=ranges,.default_size={size},.recommend_aa=false}};']
        (OUT / f'{name}.c').write_text('\n'.join(lines)+'\n')
        declarations.append(f'extern const pax_font_t {name};')
        aliases.append(f'#define CHRONOS_FONT_{role} (&{name})')
        manifest.append(dict(file=name+'.c',source=source.name,weight={'Regular':400,'Medium':500,'SemiBold':600}[weight],size=size,bpp=4,glyphs=len(cps),bitmap_bytes=len(pixels),line_height=line_height,baseline=ascent,coverage=charset))
    header = ['/* Generated by tools/generate_fonts.py. Semantic typography for PAX. */', '#pragma once', '#include "pax_gfx.h"'] + declarations + aliases
    header += ['/* No alternate large-clock view exists; do not embed an unused 64px font. */', '#define CHRONOS_FONT_CLOCK_ALT CHRONOS_FONT_TIME_LARGE', '', 'static inline int chronos_font_size(const pax_font_t* font) { return font->default_size; }', 'static inline int chronos_font_height(const pax_font_t* font) { return font->ranges[0].bitmap_var.height; }']
    header += ['static inline int chronos_font_baseline(const pax_font_t* font) {']
    header += [f'    if (font == CHRONOS_FONT_{spec[3]}) return {meta["baseline"]};' for spec, meta in zip(SPECS, manifest)]
    header += ['    return 0;', '}']
    (ROOT / 'components/chronos_ui/include/chronos_typography.h').write_text('\n'.join(header)+'\n')
    (ASSETS / 'manifest.json').write_text(json.dumps(dict(fonts=manifest,source_sha256={p.name:hashlib.sha256(p.read_bytes()).hexdigest() for p in sorted((ASSETS/'source').glob('*.ttf'))}),indent=2)+'\n')

if __name__ == '__main__':
    main()
