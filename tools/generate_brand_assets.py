#!/usr/bin/env python3
"""Convert prepared artwork to launcher PNG sizes and flash-backed PAX data.

Requires Pillow. Run from any directory; generated outputs are checked in.
"""
from pathlib import Path
from PIL import Image

ROOT = Path(__file__).resolve().parents[1]
ASSETS = ROOT / "assets/icons"
icon = Image.open(ASSETS / "chronos-icon.png").convert("RGBA")
for size in (16, 32, 64):
    icon.resize((size, size), Image.Resampling.LANCZOS).save(ASSETS / f"icon{size}.png")

logo = Image.open(ASSETS / "chronos-logo.png").convert("RGB")
logo = logo.resize((420, 420), Image.Resampling.LANCZOS)
logo = logo.quantize(colors=256, method=Image.Quantize.MEDIANCUT)
palette = logo.getpalette()
colors = [0xff000000 | (palette[i] << 16) | (palette[i+1] << 8) | palette[i+2]
          for i in range(0, 768, 3)]
pixels = logo.tobytes()
with (ROOT / "components/chronos_ui/assets/splash.c").open("w") as out:
    out.write('/* Generated by tools/generate_brand_assets.py. */\n#include "pax_gfx.h"\n')
    out.write('const pax_col_t chronos_splash_palette[256] = {\n')
    for i in range(0, 256, 8):
        out.write('    ' + ','.join(f'0x{c:08x}' for c in colors[i:i+8]) + ',\n')
    out.write('};\nconst uint8_t chronos_splash_pixels[420 * 420] = {\n')
    for i in range(0, len(pixels), 24):
        out.write('    ' + ','.join(str(c) for c in pixels[i:i+24]) + ',\n')
    out.write('};\n')
