static void press(chronos_ui_key_t key, chronos_ui_t* ui, chronos_ui_view_t* v,
                  chronos_runtime_t* r, chronos_settings_t* s, uint64_t now) {
    chronos_local_time_t local = {.date = {v->year, v->month, v->day},
        .hour = v->minute_of_day / 60, .minute = v->minute_of_day % 60};
    chronos_screen_view(v, ui, r, s, v->year ? &local : NULL, now, NULL, v->storage_available);
    chronos_screen_key(key, ui, v, r, s, now);
}
static void test_split_display(void) {
    chronos_settings_t settings;
    chronos_settings_defaults(&settings);
    chronos_runtime_t runtime;
    assert(chronos_runtime_init(&runtime, &settings));
    chronos_ui_t ui = {.active = 2, .content = true, .row = 0};
    chronos_ui_view_t v = {0};
    press(UI_F4, &ui, &v, &runtime, &settings, 0);
    chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 1200000, NULL, true);
    press(UI_TAB, &ui, &v, &runtime, &settings, 1200000);
    chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 2000000, NULL, true);
    assert(v.count == 1);
    assert(!strcmp(v.detail[0], "Segment 00:01.2 / Total 00:01.2"));
    assert(strstr(v.heading, "00:02.0"));
    press(UI_TAB, &ui, &v, &runtime, &settings, 3500000);
    chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 3500000, NULL, true);
    assert(!strcmp(v.detail[0], "Segment 00:02.3 / Total 00:03.5"));
    assert(!strcmp(v.detail[1], "Segment 00:01.2 / Total 00:01.2"));
    press(UI_F2, &ui, &v, &runtime, &settings, 4000000);
    press(UI_TAB, &ui, &v, &runtime, &settings, 5000000);
    chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 5000000, NULL, true);
    assert(v.count == 2 && v.rows[0].verb == UI_NONE);
    press(UI_F2, &ui, &v, &runtime, &settings, 6000000);
    for (unsigned i = 0; i < 12; ++i)
        press(UI_TAB, &ui, &v, &runtime, &settings, 7000000 + i * 1000000);
    chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 18000000, NULL, true);
    assert(v.count == 10 && v.count <= CHRONOS_UI_ROWS);
    assert(!strcmp(v.detail[0], "Segment 00:01.0 / Total 00:16.0"));
    assert(!strcmp(v.detail[9], "Segment 00:01.0 / Total 00:07.0"));
    ui.content = true;
    for (unsigned i = 0; i < 10; ++i) chronos_ui_key(&ui, &v, UI_DOWN);
    assert(ui.row == 9 && chronos_ui_key(&ui, &v, UI_ENTER) == 0);
    ui.row = 1;
    press(UI_F3, &ui, &v, &runtime, &settings, 19000000);
    chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 19000000, NULL, true);
    assert(v.count == 0);
}
static void test_timer_controls(void) {
    for (unsigned tab = 2; tab <= 4; ++tab) {
        chronos_settings_t settings;
        chronos_settings_defaults(&settings);
        chronos_runtime_t runtime;
        assert(chronos_runtime_init(&runtime, &settings));
        chronos_ui_t ui = {.active = tab};
        chronos_ui_view_t v = {0};
        timing_session_t* session = tab == 2 ? &runtime.stopwatch.session :
                                    tab == 3 ? &runtime.countdown.session : &runtime.pacer.session;
        chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 0, NULL, true);
        assert(v.count == (tab == 2 ? 0u : 1u));
        if (tab != 2) assert(v.rows[0].verb == UI_OPEN && !strcmp(v.detail[0], "Configuration"));
        press(UI_F2, &ui, &v, &runtime, &settings, 0);
        assert(session->state == TIMING_IDLE);
        press(UI_F4, &ui, &v, &runtime, &settings, 0);
        press(UI_F2, &ui, &v, &runtime, &settings, 1000000);
        assert(session->state == TIMING_PAUSED);
        press(UI_F2, &ui, &v, &runtime, &settings, 3000000);
        assert(session->state == TIMING_RUNNING);
        press(UI_F4, &ui, &v, &runtime, &settings, 4000000);
        assert(session->state == TIMING_STOPPED);
        if (tab == 4) assert(timing_pacer_poll(&runtime.pacer, 9000000) == 0);
        assert(timing_session_elapsed(session, 9000000) == 2000000);
        if (tab == 3) assert(timing_countdown_remaining(&runtime.countdown, 9000000) == 298000000);
        press(UI_F2, &ui, &v, &runtime, &settings, 9000000);
        assert(session->state == TIMING_STOPPED);
        press(UI_F4, &ui, &v, &runtime, &settings, 10000000);
        assert(session->state == TIMING_RUNNING && timing_session_elapsed(session, 10000000) == 0);
        press(UI_F2, &ui, &v, &runtime, &settings, 11000000);
        press(UI_F4, &ui, &v, &runtime, &settings, 12000000);
        assert(session->state == TIMING_STOPPED);
        press(UI_F3, &ui, &v, &runtime, &settings, 13000000);
        assert(session->state == TIMING_IDLE && session->accumulated_us == 0);
        ui.editing = true;
        press(UI_F4, &ui, &v, &runtime, &settings, 14000000);
        assert(session->state == TIMING_IDLE);
    }
}
