    chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 0, NULL, true);
    press(UI_ENTER, &ui, &v, &runtime, &settings, 0);
    assert(!ui.editing && !strcmp(settings.timezone, chronos_zone(sofia)->timezone));
    chronos_screen_command(22, &ui, &runtime, &settings, 0);
    chronos_screen_command(40, &ui, &runtime, &settings, 0);
    chronos_screen_text('0', &ui);
    press(UI_ENTER, &ui, &v, &runtime, &settings, 0);
    assert(settings.city_count == 0);
    settings.cities[0].name[0] = 0;
    chronos_screen_command(40, &ui, &runtime, &settings, 0);
    chronos_screen_text('1', &ui);
    press(UI_ENTER, &ui, &v, &runtime, &settings, 0);
    assert(settings.city_count == 1 && chronos_settings_valid(&settings));
    chronos_screen_command(41, &ui, &runtime, &settings, 0);
    assert(ui.editing && ui.editor_slot == 7);
    press(UI_RIGHT, &ui, &v, &runtime, &settings, 0);
    assert(ui.zone_page == 1);
    chronos_screen_command(1000 + (int)sofia, &ui, &runtime, &settings, 0);
    assert(ui.editor_slot == 2 && !strcmp(settings.cities[0].name, "Europe/Sofia"));
    chronos_screen_command(23, &ui, &runtime, &settings, 0);
    chronos_screen_command(51, &ui, &runtime, &settings, 0);
    while (ui.cursor) chronos_screen_text(8, &ui);
    chronos_screen_text('/', &ui);
    press(UI_ENTER, &ui, &v, &runtime, &settings, 0);
    chronos_screen_command(52, &ui, &runtime, &settings, 0);
    assert(ui.editing && ui.draft[1] && !ui.clock_reconfigure_requested);
    chronos_screen_command(51, &ui, &runtime, &settings, 0);
    chronos_screen_text(8, &ui);
    const char* hostname = "time.example.org";
    for (size_t i = 0; hostname[i]; ++i) chronos_screen_text(hostname[i], &ui);
    press(UI_ENTER, &ui, &v, &runtime, &settings, 0);
    chronos_screen_command(50, &ui, &runtime, &settings, 0);
    chronos_screen_command(52, &ui, &runtime, &settings, 0);
    assert(!ui.editing && ui.clock_reconfigure_requested && !settings.ntp_enabled);
    assert(!strcmp(settings.ntp_server, hostname));
    chronos_screen_command(24, &ui, &runtime, &settings, 0);
    assert(ui.settings_save_requested);
    ui.active = 6; ui.content = true;
    for (unsigned theme = 0; theme < CHRONOS_THEME_COUNT; ++theme) {
        chronos_screen_command(25, &ui, &runtime, &settings, 0);
        ui.row = theme;
        chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 0, NULL, false);
        assert(v.count == 3 && v.storage_notice);
        press(UI_ENTER, &ui, &v, &runtime, &settings, 0);
        assert((unsigned)settings.theme == theme && !ui.editing);
    }
    chronos_screen_command(25, &ui, &runtime, &settings, 0);
    press(UI_ESCAPE, &ui, &v, &runtime, &settings, 0);
    assert(settings.theme == CHRONOS_THEME_OPERATOR);
    chronos_screen_command(63, &ui, &runtime, &settings, 0);
    for (unsigned i = 0; i < 30; ++i) press(UI_RIGHT, &ui, &v, &runtime, &settings, 0);
    assert(ui.draft[0] == 100);
    chronos_screen_command(64, &ui, &runtime, &settings, 0);
    assert(settings.keyboard_percent == 100);
    chronos_screen_command(65, &ui, &runtime, &settings, 0);
    chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 0, NULL, false);
    ui.row = 1;
    press(UI_ENTER, &ui, &v, &runtime, &settings, 0);
    assert(ui.sound_scan_requested); /* Internal sounds are selectable without SD. */
    ui.sound_scan_requested = false;
    strcpy(ui.clock_server, "../bad.wav");
    chronos_screen_command(66, &ui, &runtime, &settings, 0);
    assert(ui.editing && ui.draft[1]);
    strcpy(ui.clock_server, "wake.wav");
    chronos_screen_command(66, &ui, &runtime, &settings, 0);
    assert(!ui.editing && ui.sound_reload_requested && !strcmp(settings.alarm_sound, "wake.wav"));
    chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 0, NULL, false);
    ui.row = 9;
    assert(chronos_ui_key(&ui, &v, UI_ENTER) == 0);
    assert(!strcmp(v.detail[7], "Font size"));
    press(UI_F4, &ui, &v, &runtime, &settings, 0);
    ui.settings_save_requested = false;
    chronos_screen_view(&v, &ui, &runtime, &settings, NULL, 0, NULL, true);
    press(UI_F4, &ui, &v, &runtime, &settings, 0);
    assert(ui.settings_save_requested);
    puts("UI: all tests passed");
