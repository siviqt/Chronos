static void test_option_a(void) {
    chronos_settings_t s;
    chronos_settings_defaults(&s);
    chronos_runtime_t r;
    assert(chronos_runtime_init(&r, &s));
    chronos_ui_t ui = {.active = 0, .highlighted = 6};
    chronos_ui_view_t v = {.storage_available = true};
    chronos_ui_controls_t c;
    press(UI_DOWN, &ui, &v, &r, &s, 0);
    assert(ui.active == 6 && ui.content && ui.row == 0);
    ui.row = 4;
    press(UI_DOWN, &ui, &v, &r, &s, 0);
    assert(ui.row == 4);
    press(UI_RIGHT, &ui, &v, &r, &s, 0);
    assert(ui.row == 9);
    press(UI_UP, &ui, &v, &r, &s, 0);
    press(UI_LEFT, &ui, &v, &r, &s, 0);
    assert(ui.row == 3);
    ui.row = 5;
    press(UI_UP, &ui, &v, &r, &s, 0);
    assert(!ui.content && ui.highlighted == 6);

    /* F1 and F5 use the same changed-draft protection; Stay is the default. */
    for (unsigned exit = 0; exit < 2; ++exit) for (unsigned choice = 0; choice < 3; ++choice) {
        s.pacer_period_ms = 1000;
        ui = (chronos_ui_t){.active = 4, .highlighted = 4, .content = true};
        press(UI_ENTER, &ui, &v, &r, &s, 0);
        press(UI_RIGHT, &ui, &v, &r, &s, 0);
        press(exit ? UI_F1 : UI_F5, &ui, &v, &r, &s, 0);
        assert(ui.leave_prompt && ui.leave_choice == 2 && s.pacer_period_ms == 1000);
        if (choice < 2) press(UI_UP, &ui, &v, &r, &s, 0);
        if (!choice) press(UI_UP, &ui, &v, &r, &s, 0);
        press(UI_ENTER, &ui, &v, &r, &s, 0);
        assert(!ui.leave_prompt);
        assert(s.pacer_period_ms == (choice == 0 ? 2000u : 1000u));
        if (choice == 2) assert(ui.editing && !ui.exit_requested && ui.active == 4);
        else if (exit) assert(ui.exit_requested);
        else assert(!ui.editing && ui.active == 5);
    }
    /* Invalid active input cannot be applied by the leave prompt. */
    ui = (chronos_ui_t){.active = 4, .highlighted = 4, .content = true};
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    strcpy(ui.field_text, "9999999999");
    press(UI_F5, &ui, &v, &r, &s, 0);
    press(UI_UP, &ui, &v, &r, &s, 0);
    press(UI_UP, &ui, &v, &r, &s, 0);
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    assert(ui.active == 4 && ui.editing && ui.field_edit == 5 && ui.draft[2]);
    press(UI_ESCAPE, &ui, &v, &r, &s, 0);
    assert(ui.editing && !ui.field_edit);
    press(UI_ESCAPE, &ui, &v, &r, &s, 0);
    assert(!ui.editing);

    /* NTP and sound now support F4; field cancellation restores the draft. */
    ui = (chronos_ui_t){.active = 6, .highlighted = 6, .content = true, .row = 3};
    chronos_screen_command(23, &ui, &r, &s, 0);
    ui.row = 1;
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    strcpy(ui.clock_server, "discard.example");
    press(UI_ESCAPE, &ui, &v, &r, &s, 0);
    assert(ui.editing && !strcmp(ui.clock_server, s.ntp_server));
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    strcpy(ui.clock_server, "time.example.org");
    press(UI_F4, &ui, &v, &r, &s, 0);
    assert(!ui.editing && ui.row == 3 && !strcmp(s.ntp_server, "time.example.org"));
    ui.row = 4;
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    strcpy(ui.clock_server, "../bad.wav");
    press(UI_F4, &ui, &v, &r, &s, 0);
    assert(ui.editing && !s.alarm_sound[0]);
    strcpy(ui.clock_server, "wake.wav");
    press(UI_F4, &ui, &v, &r, &s, 0);
    assert(!ui.editing && ui.row == 4 && !strcmp(s.alarm_sound, "wake.wav"));

    /* Brightness supports quick adjustment and typed editing without applying both by Enter. */
    ui.row = 6;
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    press(UI_RIGHT, &ui, &v, &r, &s, 0);
    unsigned draft = ui.draft[0];
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    chronos_screen_text('1', &ui); chronos_screen_text('0', &ui); chronos_screen_text('1', &ui);
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    assert(ui.field_edit == 7 && ui.draft[2]);
    press(UI_ESCAPE, &ui, &v, &r, &s, 0);
    assert(ui.editing && ui.draft[0] == draft && s.keyboard_percent != draft);
    press(UI_F4, &ui, &v, &r, &s, 0);
    assert(!ui.editing && ui.row == 6 && s.keyboard_percent == draft);

    /* External subpages return to their parent, not out of the draft. */
    ui.row = 8;
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    ui.external_draft.enabled = true;
    ui.external_draft.driver = EXT_DRIVER_NOKIA;
    chronos_screen_command(704, &ui, &r, &s, 0);
    ui.row = 5;
    press(UI_DOWN, &ui, &v, &r, &s, 0);
    assert(v.rows[ui.row].command == 707);
    press(UI_ESCAPE, &ui, &v, &r, &s, 0);
    assert(ui.editing && !ui.external_page);
    press(UI_F4, &ui, &v, &r, &s, 0);
    assert(!ui.editing && ui.row == 8 && s.external.enabled);

    /* Catalogue typing has local cancellation, and city catalogues return to the city list. */
    ui.row = 2;
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    ui.row = 1;
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    chronos_screen_command(902, &ui, &r, &s, 0);
    chronos_screen_text('x', &ui);
    press(UI_ESCAPE, &ui, &v, &r, &s, 0);
    assert(ui.editor_slot == 7 && !ui.field_edit && !ui.zone_search[0]);
    press(UI_ESCAPE, &ui, &v, &r, &s, 0);
    assert(ui.editing && ui.editor_slot == 2 && ui.row == 1);
    press(UI_ESCAPE, &ui, &v, &r, &s, 0);
    assert(!ui.editing && ui.row == 2);

    /* All active alert actions coexist with the current controls and full notice detail. */
    timing_stopwatch_start(&r.stopwatch, 0);
    for (unsigned tab = 0; tab < 7; ++tab) {
        ui = (chronos_ui_t){.active = tab, .highlighted = tab};
        chronos_screen_view(&v, &ui, &r, &s, NULL, 1000000, "SD unavailable", false);
        chronos_ui_controls(&ui, &v, &c);
        assert(strstr(c.secondary, "Tab Split") && strstr(c.secondary, "Bksp Notices"));
        assert(tab != 6 || !c.function[3]);
    }
    ui = (chronos_ui_t){.active = 4, .highlighted = 4, .content = true};
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    for (unsigned i = 0; i < CHRONOS_ALARM_LIMIT; ++i) {
        r.alarms.runtime[i].phase = CHRONOS_ALARM_RINGING;
        r.alarms.runtime[i].missed = true;
    }
    r.countdown.session.state = TIMING_COMPLETE;
    chronos_screen_view(&v, &ui, &r, &s, NULL, 0, "SD unavailable", false);
    chronos_ui_controls(&ui, &v, &c);
    assert(strstr(c.primary, "Type digits") && strstr(c.secondary, "Cancel field"));
    assert(v.alarm_ringing && v.notice_count == 7 && strstr(v.alert_hint, "Snooze all"));
    assert(chronos_runtime_key(&r, 'a', 0));
    chronos_screen_view(&v, &ui, &r, &s, NULL, 0, "SD unavailable", false);
    assert(!v.alarm_ringing && strstr(v.alert_hint, "Space Clear"));
    press(UI_ESCAPE, &ui, &v, &r, &s, 0);
    chronos_screen_text(8, &ui);
    assert(ui.notifications && ui.editing);
    for (unsigned i = 0; i < 10; ++i) press(UI_DOWN, &ui, &v, &r, &s, 0);
    assert(ui.notice_row == v.notice_count - 1);
    press(UI_ESCAPE, &ui, &v, &r, &s, 0);
    assert(!ui.notifications && ui.editing);
    press(UI_RIGHT, &ui, &v, &r, &s, 0);
    chronos_screen_text(8, &ui);
    press(UI_F5, &ui, &v, &r, &s, 0);
    assert(ui.leave_prompt && ui.notifications);
    press(UI_UP, &ui, &v, &r, &s, 0);
    press(UI_UP, &ui, &v, &r, &s, 0);
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    assert(ui.active == 5 && !ui.editing && !ui.notifications);
    ui = (chronos_ui_t){.active = 1, .highlighted = 1, .content = true};
    press(UI_ENTER, &ui, &v, &r, &s, 0);
    ui.field_edit = 3; ui.draft[9] = 0;
    chronos_screen_view(&v, &ui, &r, &s, NULL, 0, NULL, true);
    assert(strstr(v.error, "at least one weekday"));
    chronos_screen_text(8, &ui);
    assert(ui.notifications);
    chronos_screen_text(8, &ui);
    assert(!ui.notifications && ui.field_edit == 3);
}

